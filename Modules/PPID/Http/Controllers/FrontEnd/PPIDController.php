namespace Modules\PPID\Http\Controllers\FrontEnd;

use Modules\PPID\Models\Menu;
use WebModulController;

defined('BASEPATH') || exit('No direct script access allowed');

class PPIDController extends WebModulController
{
    public function __construct()
    {
        parent::__construct();
        view()->share('moduleJson', $this->loadModuleJson());
        view()->share('menuPPID', $this->menu());
    }

    private function menu()
    {
        $settingMenu = setting('ppid_website_menu') ?? 'OpenSID';

        return $settingMenu == 'OpenSID' ? menu_tema() : $this->menuPpid();

    }

    private function menuPpid()
    {
        return cache()->rememberForever('menu_ppid', static fn () => (new Menu())->tree()->toArray());
    }
}
